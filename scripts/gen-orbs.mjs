// Bakes the thinking-orbs animations WEAVE's map uses (MIT, see THIRD_PARTY_NOTICES.md) into plain frame data,
// so the Claude Code mod can draw the same dots as SVG without bundling the engine.
import { writeFileSync } from "node:fs";
import { MODE_FRAMES, resolvePreset } from "thinking-orbs/engine";

const ORB = { Read: "searching", Edit: "composing", Run: "working", PR: "weaving" };
const SIZE = 20, FRAMES = 12, SECONDS = 1.6;
const out = {};
for (const [verb, state] of Object.entries(ORB)) {
  const { mode, speed, opts } = resolvePreset(state, SIZE);
  out[verb] = Array.from({ length: FRAMES }, (_, i) => {
    const f = MODE_FRAMES[mode](SIZE, (i / FRAMES) * SECONDS * speed, opts);
    // [x, y, radius, opacity]: nearer dots (lower white) are stronger, as the map paints them.
    const w = (d) => d.r * (d.a ?? 1);
    return [...f.dots].sort((a, b) => w(b) - w(a)).slice(0, 36).sort((a, b) => a.z - b.z).map((d) => [d.x, d.y, d.r, (d.a ?? 1) * (0.35 + 0.65 * (1 - Math.min(1, Math.max(0, d.white))))].map((n, k) => Math.round(n * (k === 3 ? 100 : 10)) / (k === 3 ? 100 : 10)));
  });
}
writeFileSync(new URL("../mods/weave-panel/hooks/orbs.ts", import.meta.url),
  `// Generated by scripts/gen-orbs.mjs from thinking-orbs (MIT, Copyright (c) 2026 Jakub Antalik). Do not edit.\nexport const ORB_SECONDS = ${SECONDS}\nexport const ORB_FRAMES: Record<string, number[][][]> = ${JSON.stringify(out)}\n`);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, v.map((f) => f.length).join(",")])));
